    // DASH-T acceptance 2 (determinism lock): a flat dash world (no terrain) is tick for tick what it was before DASH-T. Unit 1
    // (the M7a dasher, 20 m in 10 ticks, cooldown 60) walks from (5.5, 12.5) toward (60.5, 6.5) round the wall at x 40..41
    // (z 0..20); unit 2 stands at (30.5, 22.5). Requests: tick 1 along (3, 0, 1) (a whole dash, then the order again), tick 30
    // along -X (refused, cooling down), tick 70 along +X (into the wall: ends after its first step), tick 140 along -Z (into the
    // map edge: ends early, then the order again). Recorded on main f4da976, before the first DASH-T change. Never edit by hand.
    public sealed class DashTFlatLockTests
    {
        internal const int Length = 200;

        internal static SimSession Open() =>
            DashWorlds.World(new[] { DashWorlds.Dasher(1, 5500, 12500), DashWorlds.Plain(2, 30500, 22500) }, DashWorlds.Map((40, 0, 1, 20)),
                new[] { BridgeCommand.MoveTo(1, 1, 60500, 6500) });

        // The request made before the step of tick t + 1, at clock tick t.
        internal static void Ask(SimSession s)
        {
            long t = DashWorlds.Tick(s);
            if (t == 1) DashWorlds.Dash(s, SimVec3.Metres(3, 0, 1));
            else if (t == 30) DashWorlds.Dash(s, DashWorlds.MinusX);
            else if (t == 70) DashWorlds.Dash(s, DashWorlds.PlusX);
            else if (t == 140) DashWorlds.Dash(s, SimVec3.Metres(0, 0, -1));
        }

        [Test]
        public void FlatDashWorld_IsUnchangedTickForTick()
        {
            SimSession s = Open();
            var stopped = new List<long>();
            for (int t = 1; t <= Length; t++)
            {
                Ask(s);
                s.StepOnce();
                SimVec3 p = M3TestWorld.Position(s);
                Assert.That((p.X.Raw, p.Z.Raw), Is.EqualTo((Track[2 * t - 2], Track[2 * t - 1])), "position after tick " + t);
                Assert.That(s.StateHash, Is.EqualTo(Hashes[t - 1]), "state hash after tick " + t);
                Assert.That(p.Y.Raw, Is.Zero);
            }
            Assert.That(M3TestWorld.Position(s, 2), Is.EqualTo(new SimVec3(SimFix.Ratio(61, 2), default, SimFix.Ratio(45, 2))));
        }

